package com.domrei.skinview

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Matrix
import android.graphics.Paint
import android.graphics.Rect
import androidx.annotation.DrawableRes
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.InputStream
import java.net.HttpURLConnection
import java.net.URL

/** Helpers to load and normalize Minecraft skin / cape textures. */
object SkinUtils {

    /** Decode a skin from a drawable/raw resource without density scaling. */
    fun fromResource(context: Context, @DrawableRes resId: Int): Bitmap {
        val options = BitmapFactory.Options().apply { inScaled = false }
        return requireNotNull(BitmapFactory.decodeResource(context.resources, resId, options)) {
            "Cannot decode skin resource $resId"
        }
    }

    /** Decode a skin from an asset file, e.g. `"skins/my_skin.png"`. */
    fun fromAsset(context: Context, path: String): Bitmap =
        context.assets.open(path).use { fromStream(it) }

    fun fromStream(stream: InputStream): Bitmap =
        requireNotNull(BitmapFactory.decodeStream(stream)) { "Cannot decode skin stream" }

    /**
     * Download a texture. Requires the `android.permission.INTERNET` permission in the app manifest.
     */
    suspend fun fromUrl(url: String): Bitmap = withContext(Dispatchers.IO) {
        val connection = URL(url).openConnection() as HttpURLConnection
        try {
            connection.connectTimeout = 10_000
            connection.readTimeout = 10_000
            connection.instanceFollowRedirects = true
            if (connection.responseCode !in 200..299) {
                error("HTTP ${connection.responseCode} while loading $url")
            }
            connection.inputStream.use { fromStream(it) }
        } finally {
            connection.disconnect()
        }
    }

    /**
     * Converts any supported skin to a 64x64-style (1.8+) texture:
     * - 64x32 legacy skins get left arm/leg generated by mirroring the right ones.
     * - High-resolution skins (128x128, 128x64, ...) are kept at their resolution.
     */
    fun normalizeSkin(skin: Bitmap): Bitmap {
        val w = skin.width
        val h = skin.height
        require(w > 0 && w % 64 == 0) { "Skin width must be a multiple of 64, was $w" }
        require(h == w || h * 2 == w) { "Skin must be 64x64 or 64x32 (or a multiple), was ${w}x$h" }

        val src = if (skin.config == Bitmap.Config.ARGB_8888) skin else skin.copy(Bitmap.Config.ARGB_8888, false)
        if (h == w) return src

        val scale = w / 64
        val out = Bitmap.createBitmap(w, w, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(out)
        canvas.drawBitmap(src, 0f, 0f, null)

        fun mirror(sx: Int, sy: Int, sw: Int, sh: Int, dx: Int, dy: Int) {
            val part = Bitmap.createBitmap(src, sx * scale, sy * scale, sw * scale, sh * scale)
            val m = Matrix().apply { preScale(-1f, 1f) }
            val flipped = Bitmap.createBitmap(part, 0, 0, part.width, part.height, m, false)
            canvas.drawBitmap(flipped, (dx * scale).toFloat(), (dy * scale).toFloat(), null)
        }
        // Leg: top, bottom, outer, front, inner, back
        mirror(4, 16, 4, 4, 20, 48)
        mirror(8, 16, 4, 4, 24, 48)
        mirror(0, 20, 4, 12, 24, 52)
        mirror(4, 20, 4, 12, 20, 52)
        mirror(8, 20, 4, 12, 16, 52)
        mirror(12, 20, 4, 12, 28, 52)
        // Arm
        mirror(44, 16, 4, 4, 36, 48)
        mirror(48, 16, 4, 4, 40, 48)
        mirror(40, 20, 4, 12, 40, 52)
        mirror(44, 20, 4, 12, 36, 52)
        mirror(48, 20, 4, 12, 32, 52)
        mirror(52, 20, 4, 12, 44, 52)
        return out
    }

    /**
     * Detects the slim (Alex) model: in slim skins the 4th pixel column of the right arm
     * (x 50..51 top and 54..55 front/side) is fully transparent.
     */
    fun isSlim(skin: Bitmap): Boolean {
        if (skin.width != skin.height) return false
        val s = skin.width / 64
        fun transparent(x: Int, y: Int, w: Int, h: Int): Boolean {
            for (py in y * s until (y + h) * s) for (px in x * s until (x + w) * s) {
                if ((skin.getPixel(px, py) ushr 24) != 0) return false
            }
            return true
        }
        return transparent(50, 16, 2, 4) && transparent(54, 20, 2, 12)
    }

    /** Scales a cape to a 64x32-based texture. Supports 22x17 legacy capes and 64x32 multiples. */
    fun normalizeCape(cape: Bitmap): Bitmap {
        if (cape.width % 64 == 0 && cape.width == cape.height * 2) return cape
        // Legacy 22x17 (or multiples): place on a 64x32 canvas.
        val scale = maxOf(1, cape.width / 22)
        val out = Bitmap.createBitmap(64 * scale, 32 * scale, Bitmap.Config.ARGB_8888)
        Canvas(out).drawBitmap(
            cape,
            Rect(0, 0, cape.width, cape.height),
            Rect(0, 0, cape.width, cape.height),
            Paint(),
        )
        return out
    }
}
